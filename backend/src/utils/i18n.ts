const CATALOGUES: Record<Language, Catalogue> = {
  [Language.AR]: ar,
  [Language.EN]: en,
  [Language.TR]: tr,
};

export const SUPPORTED_LANGUAGES: readonly Language[] = [Language.AR, Language.EN, Language.TR];

export function isSupportedLanguage(value: unknown): value is Language {
  return typeof value === 'string' && SUPPORTED_LANGUAGES.includes(value as Language);
}

function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );
}

/**
 * Renders a message key in the requested language.
 * Falls back: requested -> English -> the key itself (so a missing key is
 * visible in QA instead of silently rendering an empty string).
 */
export function t(language: Language, key: string, params?: MessageParams): string {
  const template = CATALOGUES[language]?.[key] ?? CATALOGUES[Language.EN][key] ?? key;
  return interpolate(template, params);
}

/** Renders one key in all three languages - used by print/receipt payloads. */
export function tAll(key: string, params?: MessageParams): Record<Language, string> {
  return {
    [Language.AR]: t(Language.AR, key, params),
    [Language.EN]: t(Language.EN, key, params),
    [Language.TR]: t(Language.TR, key, params),
  };
}

/** Development helper: reports keys missing from a non-English catalogue. */
export function findMissingKeys(): Record<string, string[]> {
  const reference = Object.keys(en);
  const report: Record<string, string[]> = {};
  for (const language of SUPPORTED_LANGUAGES) {
    const missing = reference.filter((key) => !(key in CATALOGUES[language]));
    if (missing.length > 0) report[language] = missing;
  }
  return report;
}
